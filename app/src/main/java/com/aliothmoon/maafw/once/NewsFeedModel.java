package com.aliothmoon.maafw.once;

import com.aliothmoon.maafw.once.NativeUiBoundPointsParser.Node;
import com.aliothmoon.maafw.rewards.RewardRegionLocator.Box;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/** Interprets a single owned Bing tree. Its boxes are observations, never input authority. */
final class NewsFeedModel {
    enum Page { REWARDS, FEED, ARTICLE, BLOCKED, UNKNOWN }
    enum Kind { ENTRY, ARTICLE, AD, UNKNOWN }

    // A candidate supplies geometry only. Its visual identity is generated by the same-card crop.
    record Card(Kind kind, Box box, Box source, Box title, String publisher, String headline,
                String key, String layoutKey, Box image) { }
    record Frame(Page page, Box viewport, Box entry, boolean entryComplete, Card card,
                 int stride, boolean atEnd, String reason) { }

    private static final Set<String> END_LABELS = Set.of("已到列表底部","没有更多内容了","没有更多新闻","no more stories");

    static Frame inspect(List<Node> nodes, int width, int height, int anchorY, Card opened) {
        if (width < 128 || height < 128 || width > 8192 || height > 8192) return unknown("DISPLAY");
        Tree tree = Tree.create(nodes);
        if (tree == null) return unknown("TREE");
        var guard = new LiveVisitGuard.Accumulator();
        var ready = new NativeUiReadyDiagnostics.Accumulator();
        for (Node n : nodes) {
            if (!n.visible()) continue;
            guard.node("", n.text(), n.description(), true);
            ready.node("", n.text(), n.description());
        }
        if (guard.challenges > 0 || guard.dialogs > 0 || ready.blocked())
            return new Frame(Page.BLOCKED, null, null, false, null, 0, false, "BLOCKER");
        Box display = new Box(0, 0, width, height);
        if (tree.hasId("homePageWrapper")) return rewards(tree, display);
        // An open article may render a complete list of recommendations below its body.
        if (opened != null && opened.kind() == Kind.ARTICLE && article(tree, opened))
            return new Frame(Page.ARTICLE, display, null, false, null, 0, false, "MATCHED_ARTICLE");
        return feed(tree, display, anchorY);
    }

    private static Frame rewards(Tree tree, Box display) {
        Node home = tree.uniqueId("homePageWrapper"), panel = tree.uniqueId("dailyTaskPanel");
        Node section = tree.uniqueId("dailyActivities"), entry = tree.uniqueId("read");
        if (home == null || panel == null || section == null || entry == null || !home.visible()
                || panel.parentIndex() != home.index() || section.parentIndex() != panel.index()
                || entry.parentIndex() != section.index()) return unknown("REWARDS_ANCESTRY");
        Box viewport = clip(bounds(home), display);
        if (viewport == null) return unknown("REWARDS_VIEWPORT");
        var bound = NativeUiBoundPointsParser.parseRegions(tree.nodes);
        var count = bound.counters().reading();
        if (count.status() == NativeUiStructureParser.Status.AMBIGUOUS) return unknown("AMBIGUOUS_ENTRY");
        Box card = bounds(entry);
        boolean full = entry.visible() && wellInside(viewport, card);
        // WebView clips an off-screen card to a zero-height rectangle. Only scrolling is possible.
        if (!full) {
            // The clipped position still distinguishes a card above the viewport from one below.
            // Do not infer a direction from the zero box emitted for a detached WebView child.
            boolean horizontal = card.width() > 0 && card.left() >= viewport.left()
                    && card.right() <= viewport.right() && card.bottom() >= card.top();
            boolean above = horizontal && card.top() <= viewport.top() && card.bottom() < viewport.bottom();
            boolean below = horizontal && card.bottom() >= viewport.bottom() && card.top() > viewport.top();
            if (above == below) return unknown("ENTRY_CLIP_POSITION");
            return new Frame(Page.REWARDS, viewport, null, false, null, 0, false,
                    above ? "ENTRY_ABOVE" : "ENTRY_BELOW");
        }
        if (bound.regions().reading() == null || count.status() != NativeUiStructureParser.Status.KNOWN)
            return unknown("ENTRY_SUMMARY");
        return new Frame(Page.REWARDS, viewport, card, count.current() == count.target(),
                null, 0, false, "READING_ENTRY");
    }

    private record Candidate(Node owner, Card card) {}

    private static Frame feed(Tree tree,Box display,int anchorY) {
        Node home=tree.uniqueId("compose_home_root"), search=tree.uniqueId("search_bar"),
                footer=tree.uniqueId("com.microsoft.bing:id/sa_main_footer");
        if(home==null||footer==null||!home.visible()||!footer.visible()||tree.below(footer,home))
            return unknown("NO_FEED_CARDS");
        Box body=clip(bounds(home),display);
        if(body==null||footer.top()<=display.height()/2||!display.contains(bounds(footer)))return unknown("FEED_VIEWPORT");
        int top;
        if(search!=null){
            if(!search.visible()||!tree.below(search,home)||!body.contains(bounds(search))
                    ||search.top()>=display.height()/4||search.bottom()>display.height()/3)
                return unknown("FEED_VIEWPORT");
            top=search.bottom();
        }else{
            top=collapsedHeaderBottom(tree,home,footer,body,display);
            if(top<0)return unknown("NO_FEED_CARDS");
        }
        for(Node n:tree.nodes)if(n.visible()&&n.parentIndex()==home.index()&&n.top()==body.top()
                &&n.left()==body.left()&&n.right()==body.right()&&n.bottom()<=display.height()/4)
            top=Math.max(top,n.bottom());
        Box view=clip(body,new Box(body.left(),top,body.right(),footer.top()));
        if(view==null)return unknown("FEED_VIEWPORT");
        List<Candidate> slots=new ArrayList<>();
        for(Node n:tree.nodes){
            if(!n.visible()||!n.clickable()||!tree.below(n,home)||(search!=null&&tree.below(n,search))
                    ||n==search||bounds(n).width()<body.width()*0.65||n.right()>body.right()
                    ||n.left()<body.left()||n.bottom()<=view.top()||n.top()>=view.bottom())continue;
            Card slot=describe(tree,n,view);
            if(slot!=null)slots.add(new Candidate(n,slot));
        }
        slots.sort(Comparator.comparingInt(c->c.owner().top()));
        if(slots.size()<2)return unknown("NO_VERIFIED_CARD_GROUP");
        Node list=tree.byId.get(slots.get(0).owner().parentIndex());
        while(list!=null && !tree.below(slots.get(1).owner(),list))list=tree.byId.get(list.parentIndex());
        if(list==null||!tree.below(list,home)||(search!=null&&tree.below(search,list)))return unknown("AMBIGUOUS_FEED");
        List<Card> full=new ArrayList<>();
        for(int i=0;i<slots.size();i++) {
            var slot=slots.get(i);
            if(!tree.below(slot.owner(),list))return unknown("AMBIGUOUS_FEED");
            if(i>0){
                var prev=slots.get(i-1);
                if(tree.directBranch(slot.owner(),list)==tree.directBranch(prev.owner(),list)
                        ||prev.owner().bottom()>slot.owner().top()
                        ||Math.abs(prev.owner().left()-slot.owner().left())>Math.max(4,body.width()/50)
                        ||Math.abs(prev.owner().right()-slot.owner().right())>Math.max(4,body.width()/50))
                    return unknown("AMBIGUOUS_FEED");
            }
            if(slot.card().kind()==Kind.ARTICLE && wellInside(view,slot.card().box()))full.add(slot.card());
        }
        if(full.isEmpty())return unknown("NO_COMPLETE_ANCHORED_CARD");
        int anchor=anchorY<0?(int)full.get(0).box().centerY():anchorY;
        Card chosen=null;
        for(Card c:full){
            if(anchor<c.box().top()||anchor>=c.box().bottom())continue;
            if(chosen!=null)return unknown("AMBIGUOUS_ANCHOR");
            chosen=c;
        }
        if(chosen==null)return unknown("NO_COMPLETE_ANCHORED_CARD");
        int slot=0;
        while(slots.get(slot).card()!=chosen)slot++;
        Box previous=slot==0?null:slots.get(slot-1).card().box();
        Box next=slot+1<slots.size()?slots.get(slot+1).card().box():null;
        int gap=next!=null?next.top()-chosen.box().bottom():chosen.box().top()-previous.bottom();
        if(gap<0||gap>chosen.box().height()/3)return unknown("FEED_STRIDE");
        int stride=chosen.box().height()+gap;
        boolean end=slot==slots.size()-1 && tree.nodes.stream().anyMatch(n->n.visible()
                && bounds(n).top()>=slots.get(slots.size()-1).card().box().bottom()&&view.contains(bounds(n))
                && END_LABELS.contains(value(n)));
        // A rotating hero belongs to an additional nested pager. It is a valid list witness,
        // but its content can change several times while mobile OCR or a tap is being prepared.
        Node owner=slots.get(slot).owner(), direct=tree.directBranch(owner,list);
        if(covered(tree,owner,chosen)){
            Card blocked=new Card(Kind.UNKNOWN,chosen.box(),chosen.source(),chosen.title(),chosen.publisher(),chosen.headline(),
                    chosen.key(),chosen.layoutKey(),chosen.image());
            return new Frame(Page.FEED,view,null,false,blocked,stride,end,"FEED_OCCLUDED");
        }
        Node parent=tree.byId.get(owner.parentIndex());
        boolean carousel=parent!=null && parent!=direct && bounds(parent).equals(chosen.box());
        return new Frame(Page.FEED,view,null,false,chosen,stride,end,
                carousel?"FEED_CAROUSEL_CANDIDATE":"FEED_CANDIDATE");
    }

    private static boolean covered(Tree tree,Node owner,Card card){
        int x=(int)card.image().centerX(),y=(int)card.image().centerY();
        boolean pictureSeen=false,cardSummarySeen=false;
        for(Node n:tree.nodes){
            if(!n.visible()||n==owner||n.left()>x||x>=n.right()||n.top()>y||y>=n.bottom()
                    ||tree.below(owner,n))continue;
            if(!n.clickable()&&n.parentIndex()==owner.index()){
                // The accessibility representation of the card includes its own full-card
                // summary and photograph. A second superimposed surface is not either one.
                if(!pictureSeen&&bounds(n).equals(card.image())){pictureSeen=true;continue;}
                if(!cardSummarySeen&&bounds(n).equals(card.box())){cardSummarySeen=true;continue;}
            }
            // Accessibility traversal indices are not reliable Android z-order. An unrelated
            // visible surface covering the exact tap point cannot be proved to be behind it.
            return true;
        }
        return false;
    }

    private static int collapsedHeaderBottom(Tree tree,Node home,Node footer,Box body,Box display){
        // On a scrolled Bing home the toolbar node disappears. Its narrow full-width edge remains
        // a direct child of Compose; the Android footer remains in a separate branch of content.
        Node content=tree.uniqueId("android:id/content"),container=tree.uniqueId("com.microsoft.bing:id/container");
        if(tree.hasId("search_bar")||content==null||container==null||!content.visible()||!container.visible()
                ||!tree.below(home,container)||!tree.below(container,content)||!tree.below(footer,content)
                ||tree.below(footer,container)||!body.equals(display))return -1;
        int bottom=body.top();
        boolean fullWidthEdge=false;
        for(Node n:tree.nodes)if(n.parentIndex()==home.index()&&n.visible()&&!n.clickable()
                &&n.top()==body.top()&&n.bottom()>n.top()&&n.bottom()-n.top()<=Math.max(2,display.height()/48)){
            if(n.left()==body.left()&&n.right()==body.right()){
                if(fullWidthEdge)return -1;
                fullWidthEdge=true;
            }
            // The centered progress indicator extends below the collapsed edge.
            bottom=Math.max(bottom,n.bottom());
        }
        if(fullWidthEdge)return bottom;
        // Android may retain the complete collapsed toolbar as non-visible semantics. These
        // siblings bound the excluded chrome only; visible news cards still prove the feed.
        int thin=Math.max(2,display.height()/48),edgeBottom=-1,indicatorBottom=-1,toolbarBottom=-1;
        boolean visibleContent=false;
        for(Node n:tree.nodes){
            if(n.parentIndex()!=home.index()||n.clickable()||n.top()!=body.top())continue;
            Box box=bounds(n);
            if(!positive(box)||!body.contains(box))continue;
            if(n.visible()){
                if(box.equals(body))visibleContent=true;
                continue;
            }
            if(box.width()==body.width()){
                if(box.height()<=thin){
                    if(edgeBottom>=0)return -1;
                    edgeBottom=box.bottom();
                }else if(box.height()<=display.height()/4){
                    if(toolbarBottom>=0)return -1;
                    toolbarBottom=box.bottom();
                }
            }else if(box.height()<=thin && box.width()>=box.height() && box.width()<=body.width()/12
                    && Math.abs(box.centerX()-body.centerX())<=1){
                if(indicatorBottom>=0)return -1;
                indicatorBottom=box.bottom();
            }
        }
        if(!visibleContent||edgeBottom<0||indicatorBottom<=edgeBottom||toolbarBottom<indicatorBottom)return -1;
        return Math.max(bottom,indicatorBottom);
    }

    private static Card describe(Tree tree,Node owner,Box view){
        Box card=bounds(owner),image=null;
        boolean composite=false;
        for(Node n:tree.nodes){
            if(!n.visible()||n.parentIndex()!=owner.index()||n.clickable())continue;
            Box b=bounds(n);
            if(!positive(b)||!card.contains(b))continue;
            if(b.equals(card)){composite=true;continue;}
            if(b.width()<card.width()*.65||b.width()>=card.width()||b.height()<card.width()*.12
                    || b.top()>card.top()+card.width()*.16||Math.abs(b.centerX()-card.centerX())>card.width()*.12)continue;
            if(image!=null && !b.equals(image))return null;
            image=b;
        }
        if(!composite||image==null)return null;
        Box metadata=null;
        if(wellInside(view,card)){
            for(Node n:tree.nodes){
                if(!n.visible()||n.parentIndex()!=owner.index()||n.clickable()
                        ||n.classRole()!=NativeUiBoundPointsParser.ClassRole.TEXT)continue;
                Box b=bounds(n);
                if(!positive(b)||!card.contains(b)||b.top()<image.bottom()-2||b.top()>image.bottom()+card.width()/7
                        ||b.height()>card.width()/7||b.left()>card.left()+card.width()/3)continue;
                if(metadata==null||b.top()<metadata.top())metadata=b;
            }
        }
        Box badge=null;
        if(metadata!=null){
            int lineCenter=(int)metadata.centerY();
            int halfHeight=Math.max(8,metadata.height()/2);
            badge=new Box(card.left()+card.width()/24,Math.max(image.bottom()+1,lineCenter-halfHeight),
                    card.left()+card.width()/5,Math.min(card.bottom()-1,lineCenter+halfHeight));
            if(!positive(badge))badge=null;
        }
        String layout=LiveCardIdentity.hashText("news-layout|"+card+"|"+image+"|"+badge);
        return new Card(badge==null?Kind.UNKNOWN:Kind.ARTICLE,card,badge,null,"","","",layout,image);
    }

    private static boolean article(Tree tree,Card opened){
        if(opened.image()==null||tree.hasId("compose_home_root")||tree.hasId("homePageWrapper"))return false;
        Node host=null;
        for(Node n:tree.nodes){
            String id=n.resourceId()==null?"":n.resourceId().replaceFirst("^com\\.microsoft\\.bing:id/","");
            if(!n.visible()||!Set.of("article_body","articleBody","article-body","news_article_content").contains(id))continue;
            if(host!=null)return false;
            host=n;
        }
        if(host==null||host.clickable()||!positive(bounds(host)))return false;
        int blocks=0;
        for(Node n:tree.nodes)if(n.visible() && n.classRole()==NativeUiBoundPointsParser.ClassRole.TEXT
                && tree.below(n,host)&&!tree.insideLink(n)&&bounds(host).contains(bounds(n))
                &&bounds(n).width()>bounds(host).width()/2&&bounds(n).height()>0)blocks++;
        return blocks>=2;
    }

    static Box bounds(Node n) {return new Box(n.left(),n.top(),n.right(),n.bottom());}
    static boolean positive(Box b){return b!=null && b.width()>0 && b.height()>0;}
    private static Box clip(Box a,Box b) {
        if(!positive(a)||!positive(b))return null;
        Box result=new Box(Math.max(a.left(),b.left()),Math.max(a.top(),b.top()),
                Math.min(a.right(),b.right()),Math.min(a.bottom(),b.bottom()));
        return positive(result)?result:null;
    }
    private static boolean wellInside(Box v,Box b){return positive(b) && v.contains(b) && b.top()>v.top() && b.bottom()<v.bottom();}
    private static String value(Node n) {
        String t=LiveCardIdentity.normalize(n.text()), d=LiveCardIdentity.normalize(n.description());
        return !t.isEmpty()?t:d;
    }
    private static Frame unknown(String why){return new Frame(Page.UNKNOWN,null,null,false,null,0,false,why);}

    private static final class Tree {
        final List<Node> nodes;
        final Map<Integer,Node> byId=new HashMap<>();
        Tree(List<Node> nodes){this.nodes=nodes;}
        static Tree create(List<Node> nodes) {
            if(nodes==null||nodes.isEmpty()||nodes.size()>512)return null;
            Tree tree=new Tree(nodes);
            Map<Integer,Integer>depths=new HashMap<>();
            int roots=0,chars=0;
            for(Node n:nodes) {
                if(n==null||!n.packageMatches()||n.index()<0||tree.byId.containsKey(n.index()))return null;
                Integer d=n.parentIndex()==-1?Integer.valueOf(0):depths.get(n.parentIndex());
                if(d==null||d>32)return null;
                if(n.parentIndex()==-1){if(++roots>1||!n.visible()||!positive(bounds(n)))return null;}
                else d++;
                if(d>32)return null;
                for(String field:new String[]{n.text(),n.description(),n.resourceId()}){
                    if(field!=null){if(field.length()>2048)return null;chars+=field.length();}
                }
                if(chars>131072)return null;
                depths.put(n.index(),d);tree.byId.put(n.index(),n);
            }
            return roots==1?tree:null;
        }
        boolean below(Node n,Node parent){
            for(Node p=byId.get(n.parentIndex());p!=null;p=byId.get(p.parentIndex()))
                if(p.index()==parent.index())return true;
            return false;
        }
        boolean insideLink(Node n){for(Node at=n;at!=null;at=byId.get(at.parentIndex()))if(at.clickable())return true;return false;}
        Node directBranch(Node child,Node parent){
            Node at=child;
            while(at!=null && at.parentIndex()!=parent.index())at=byId.get(at.parentIndex());
            return at;
        }
        boolean hasId(String id){return nodes.stream().anyMatch(n->id.equals(n.resourceId()));}
        Node uniqueId(String id){Node found=null;for(Node n:nodes)if(id.equals(n.resourceId())){
            if(found!=null)return null;found=n;}return found;}
    }
    private NewsFeedModel(){}
}
